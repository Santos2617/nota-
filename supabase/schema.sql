-- Fraga Sucatas 2.0: shared data, protected by Supabase Auth and RLS.
create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated, service_role;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username = lower(username)),
  email text not null unique,
  name text not null,
  role text not null default 'CLIENTE' check (role in ('ADMIN', 'CLIENTE')),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

create function private.is_admin() returns boolean language sql stable security definer
set search_path = '' as $$
  select auth.uid() is not null and exists (
    select 1 from public.profiles where id = (select auth.uid()) and role = 'ADMIN'
  );
$$;
revoke all on function private.is_admin() from public;
grant execute on function private.is_admin() to authenticated, service_role;

create policy profiles_read on public.profiles for select to authenticated
using (id = (select auth.uid()) or (select private.is_admin()));
grant select on public.profiles to authenticated;
revoke insert, update, delete on public.profiles from anon, authenticated;

create table public.customers (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  legacy_user_id bigint,
  nome text not null check (length(trim(nome)) > 0),
  cpf_cnpj text default '', telefone text default '', whatsapp text default '',
  email text default '', endereco text default '', cidade text default '',
  estado text default '', cep text default '',
  created_at timestamptz not null default now()
);
create index customers_user_idx on public.customers(user_id);
create index customers_legacy_user_idx on public.customers(legacy_user_id);
alter table public.customers enable row level security;
create policy customers_read on public.customers for select to authenticated
using (user_id = (select auth.uid()) or (select private.is_admin()));
create policy customers_admin_write on public.customers for all to authenticated
using ((select private.is_admin())) with check ((select private.is_admin()));

create sequence public.note_number_seq;
create table public.notes (
  id bigint generated by default as identity primary key,
  public_id text not null unique default gen_random_uuid()::text,
  numero_nota text not null unique default
    ('FS-' || to_char(now() at time zone 'America/Fortaleza', 'YYYY') || '-' || lpad(nextval('public.note_number_seq')::text, 6, '0')),
  customer_id bigint not null references public.customers(id) on delete restrict,
  data_compra text not null,
  descricao text default '', observacoes text default '',
  valor_total numeric(14,2) not null default 0 check (valor_total >= 0),
  status text not null default 'VALIDA' check (status in ('VALIDA','INVALIDADA','PENDENTE')),
  public_visible_value boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  validated_at timestamptz, validated_by text
);
create index notes_customer_idx on public.notes(customer_id);
alter table public.notes enable row level security;
create policy notes_read on public.notes for select to authenticated using (
  (select private.is_admin()) or exists (
    select 1 from public.customers c where c.id = customer_id and c.user_id = (select auth.uid())
  )
);
create policy notes_admin_write on public.notes for all to authenticated
using ((select private.is_admin())) with check ((select private.is_admin()));

create table public.note_items (
  id bigint generated by default as identity primary key,
  note_id bigint not null references public.notes(id) on delete cascade,
  descricao text not null check (length(trim(descricao)) > 0),
  quantidade numeric(12,3) not null check (quantidade > 0),
  valor_unitario numeric(14,2) not null check (valor_unitario >= 0),
  valor_total numeric(14,2) generated always as (round(quantidade * valor_unitario, 2)) stored
);
create index note_items_note_idx on public.note_items(note_id);
alter table public.note_items enable row level security;
create policy items_read on public.note_items for select to authenticated using (
  (select private.is_admin()) or exists (
    select 1 from public.notes n join public.customers c on c.id = n.customer_id
    where n.id = note_id and c.user_id = (select auth.uid())
  )
);
create policy items_admin_write on public.note_items for all to authenticated
using ((select private.is_admin())) with check ((select private.is_admin()));

