-- The trigger records metadata only; CPF and addresses are not copied into logs.
create function private.audit_change() returns trigger language plpgsql security definer
set search_path = '' as $$
declare actor public.profiles;
begin
  if auth.uid() is null then return null; end if;
  select * into actor from public.profiles where id = auth.uid();
  insert into public.audit_logs(user_name,user_role,action,target_type,target_id,details)
  values (coalesce(actor.name,'Usuário'),coalesce(actor.role,'CLIENTE'),TG_OP,TG_TABLE_NAME,
    case when TG_OP = 'DELETE' then old.id::text else new.id::text end, 'Alteração salva no banco compartilhado');
  return null;
end;
$$;
revoke all on function private.audit_change() from public, anon, authenticated;
create trigger audit_customers after insert or update or delete on public.customers for each row execute function private.audit_change();
create trigger audit_notes after insert or update or delete on public.notes for each row execute function private.audit_change();
create trigger audit_company after insert or update or delete on public.company_settings for each row execute function private.audit_change();
create trigger audit_portfolio after insert or update or delete on public.portfolio_items for each row execute function private.audit_change();

-- One transaction creates/edits both the note and its items.
create function public.save_note(payload jsonb, note_id_input bigint default null) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare saved public.notes; item jsonb;
begin
  if auth.uid() is null or not private.is_admin() then raise exception 'Acesso negado'; end if;
  perform pg_advisory_xact_lock(7242907);
  if jsonb_typeof(payload->'itens') is distinct from 'array' or jsonb_array_length(payload->'itens') = 0 then
    raise exception 'Adicione pelo menos um item';
  end if;
  if coalesce(payload->>'data_compra','') !~ '^\d{2}/\d{2}/\d{4}$' then raise exception 'Informe a data no formato DD/MM/AAAA'; end if;
  if note_id_input is null then
    insert into public.notes(customer_id,data_compra,descricao,observacoes,public_visible_value,validated_at,validated_by)
    values ((payload->>'customer_id')::bigint,payload->>'data_compra',coalesce(payload->>'descricao',''),
      coalesce(payload->>'observacoes',''),coalesce((payload->>'public_visible_value')::boolean,true),now(),
      (select name from public.profiles where id = auth.uid())) returning * into saved;
  else
    update public.notes set customer_id=(payload->>'customer_id')::bigint,data_compra=payload->>'data_compra',
      descricao=coalesce(payload->>'descricao',''),observacoes=coalesce(payload->>'observacoes',''),
      public_visible_value=coalesce((payload->>'public_visible_value')::boolean,true),updated_at=now()
    where id=note_id_input returning * into saved;
    if not found then raise exception 'Nota não encontrada'; end if;
    delete from public.note_items where note_id=note_id_input;
  end if;
  for item in select * from jsonb_array_elements(payload->'itens') loop
    insert into public.note_items(note_id,descricao,quantidade,valor_unitario)
    values(saved.id,trim(item->>'descricao'),(item->>'quantidade')::numeric,(item->>'valor_unitario')::numeric);
  end loop;
  update public.notes set valor_total=(select sum(valor_total) from public.note_items where note_id=saved.id)
  where id=saved.id returning * into saved;
  return jsonb_build_object('success',true,'id',saved.id,'public_id',saved.public_id,'numero_nota',saved.numero_nota,
    'message','Nota ' || saved.numero_nota || ' salva com sucesso.');
end;
$$;
revoke all on function public.save_note(jsonb,bigint) from public, anon;
grant execute on function public.save_note(jsonb,bigint) to authenticated;

-- Only the server may access legacy password hashes during the first login.
create table private.legacy_users (
  id bigint primary key, username text unique not null, email text unique not null,
  name text not null, role text not null, password_hash text,
  migrated_user_id uuid references auth.users(id), created_at timestamptz not null default now()
);
create index legacy_users_migrated_idx on private.legacy_users(migrated_user_id);
alter table private.legacy_users enable row level security;
grant all on private.legacy_users to service_role;
-- Called only by the Auth table trigger, never as a browser RPC.
create function private.create_profile() returns trigger language plpgsql security definer
set search_path = '' as $$
declare login_name text; legacy_id bigint;
begin
  login_name := lower(trim(new.raw_user_meta_data->>'username'));
  if login_name is null or login_name !~ '^[a-z0-9_.-]{3,60}$' then raise exception 'Nome de usuário inválido'; end if;
  legacy_id := (new.raw_app_meta_data->>'legacy_user_id')::bigint;
  if legacy_id is null and exists (select 1 from private.legacy_users where username=login_name or lower(email)=lower(new.email)) then
    raise exception 'Esta conta já existe. Use o login existente';
  end if;
  insert into public.profiles(id,username,email,name,role)
  values(new.id,login_name,lower(new.email),coalesce(nullif(trim(new.raw_user_meta_data->>'name'),''),login_name),'CLIENTE');
  if legacy_id is null then
    insert into public.customers(user_id,nome,email,cpf_cnpj,telefone,whatsapp)
    values(new.id,coalesce(nullif(trim(new.raw_user_meta_data->>'name'),''),login_name),lower(new.email),
      coalesce(new.raw_user_meta_data->>'cpf_cnpj',''),coalesce(new.raw_user_meta_data->>'telefone',''),coalesce(new.raw_user_meta_data->>'telefone',''));
  end if;
  return new;
end;
$$;
revoke all on function private.create_profile() from public, anon, authenticated;
create trigger fraga_auth_profile after insert on auth.users for each row execute function private.create_profile();
create function public.legacy_login_record(login text) returns jsonb
language sql security invoker set search_path = '' as $$
  select to_jsonb(u) from private.legacy_users u where username=lower(login) or lower(email)=lower(login) limit 1;
$$;
create function public.finish_legacy_login(legacy_id bigint, auth_id uuid) returns void
language plpgsql security invoker set search_path = '' as $$
declare old_user private.legacy_users;
begin
  select * into strict old_user from private.legacy_users where id=legacy_id for update;
  if old_user.migrated_user_id is not null and old_user.migrated_user_id <> auth_id then raise exception 'Conta já vinculada'; end if;
  insert into public.profiles(id,username,email,name,role)
    values(auth_id,old_user.username,old_user.email,old_user.name,old_user.role)
    on conflict(id) do update set role=excluded.role;
  update public.customers set user_id=auth_id where legacy_user_id=legacy_id;
  update private.legacy_users set migrated_user_id=auth_id,password_hash=null where id=legacy_id;
end;
$$;
revoke all on function public.legacy_login_record(text), public.finish_legacy_login(bigint,uuid) from public, anon, authenticated;
grant execute on function public.legacy_login_record(text), public.finish_legacy_login(bigint,uuid) to service_role;

-- Login throttling also covers the legacy password verification step.
create table private.login_attempts (key text primary key, attempts integer not null, started_at timestamptz not null);
alter table private.login_attempts enable row level security;
grant all on private.login_attempts to service_role;
create function public.allow_login(attempt_key text) returns boolean
language plpgsql security invoker set search_path = '' as $$
declare total integer;
begin
  insert into private.login_attempts as a(key,attempts,started_at) values(attempt_key,1,now())
  on conflict(key) do update set attempts=case when a.started_at < now()-interval '15 minutes' then 1 else a.attempts+1 end,
    started_at=case when a.started_at < now()-interval '15 minutes' then now() else a.started_at end
  returning attempts into total;
  return total <= 20;
end;
$$;
revoke all on function public.allow_login(text) from public, anon, authenticated;
grant execute on function public.allow_login(text) to service_role;

